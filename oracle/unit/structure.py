"""Unit cases of pdfplumber's document layer (``structure.py``, the metadata
of ``PDF.__init__``, ``Page.annots``) and of ``pycompat::codecs``, replayed
by ``crates/pdftrace/tests/structure_unit.rs``.

The ``plumber_doc`` and ``plumber_objects`` stages over the corpora are the
main check of these modules (``python -m oracle.verify --set all``,
``--set adv-structure``); this generator makes the same checks runnable by
``cargo test`` (and so by ``cargo mutants``):

- ``stages.jsonl``: ``{"in": [name, pdf, password, what, max_pages,
  entry], "out": trace}``, the ``plumber_doc`` trace of each PDF of the
  adversarial corpus ``adv-structure`` (regenerated first, from
  ``oracle/adversarial/structure.py``, its depth windows included) and of
  the files of the ``quick`` set that have a structure tree, metadata
  containers or annotations (``SAMPLE``); the ``plumber_objects`` trace of
  the files of ``adv-structure`` that have annotations (``annot-*``, its
  ``annots`` lines; the replay hands it to the Rust stage as its oracle
  input). ``entry`` is ``None`` for a trace run as ``oracle.verify`` runs
  it; the depth windows (``depth-*`` files) are also traced from one and
  two frames deeper (``entry``: the depth of the stage body), which moves
  the recursion limit through the positions it can have within a level of
  each recursion (three frames for ``asdict``, two for ``repr``).
- ``codecs.jsonl``: ``{"in": [bytes], "out": [utf-8 result, utf-16
  result]}``, ``b.decode("utf-8")`` and ``b.decode("utf-16")`` (the text, or
  the ``UnicodeDecodeError``) of generated byte strings: every short
  sequence around the boundaries of both encodings, then random ones.

Every trace runs in a process forked for it (``document.in_child``), from
the state ``py_process.jsonl`` records, as ``oracle/unit/interp.py`` does.

Usage: PDFPLUMBER_ROOT=<main checkout> <root>/.venv/bin/python -m oracle.unit.structure
"""

from __future__ import annotations

import random
import sys
from collections.abc import Iterator
from typing import Any

from ..adversarial import structure as adv_structure
from ..codegen import cmaps as codegen_cmaps
from ..corpus import cache_dir, load_set
from ..stages import plumber_doc as _plumber_doc_stage  # noqa: F401  (loaded before the children fork)
from ..stages import plumber_objects as _plumber_objects_stage  # noqa: F401
from ..stages import trace_lines
from ._common import require_oracle_python, write_cases, write_meta
from .document import in_child, process_state
from .interp import deeper_trace, entry_at

MODULE = "structure"
MAX_PAGES = 20
DEPTH_OFFSETS = (1, 2)
#: Files of the quick set at most this large are included when they have
#: a structure tree, an /Info dict holding containers, or annotations.
QUICK_MAX_BYTES = 150_000
SEED = 20261020


def interesting(path: str, password: str | None) -> bool:
    """Whether a file of the quick set exercises the document layer."""
    from pdfminer.pdfdocument import PDFDocument
    from pdfminer.pdfpage import PDFPage
    from pdfminer.pdfparser import PDFParser
    from pdfminer.pdftypes import resolve1

    try:
        with open(path, "rb") as f:
            doc = PDFDocument(PDFParser(f), password=password or "")
            if "StructTreeRoot" in doc.catalog:
                return True
            if any(isinstance(resolve1(v), (dict, list)) for info in doc.info for v in info.values()):
                return True
            for i, page in enumerate(PDFPage.create_pages(doc)):
                if i >= MAX_PAGES:
                    break
                if page.annots:
                    return True
    except Exception:
        return False
    return False


def stage_cases() -> Iterator[tuple[list, str]]:
    seen: set[str] = set()
    for set_name in ("adv-structure", "quick"):
        for f in load_set(set_name):
            if f.sha256 in seen:
                continue
            seen.add(f.sha256)
            if set_name == "quick" and (f.size > QUICK_MAX_BYTES or not in_child(lambda: interesting(str(f.path), f.password))):
                continue
            data = f.path.read_bytes()
            stages = ["plumber_doc"]
            if set_name == "adv-structure" and f.path.name[4:].startswith("annot-"):
                stages.append("plumber_objects")
            for what in stages:
                lines = in_child(lambda: trace_lines(what, str(f.path), f.password, MAX_PAGES))
                yield [f.path.name, data, f.password, what, MAX_PAGES, None], "".join(x + "\n" for x in lines)
            if not f.path.name[4:].startswith("depth-"):
                continue
            for k in DEPTH_OFFSETS:
                entry = in_child(lambda: entry_at(k))
                lines = in_child(lambda: deeper_trace("plumber_doc", str(f.path), f.password, k))
                yield [f.path.name, data, f.password, "plumber_doc", MAX_PAGES, entry], "".join(x + "\n" for x in lines)


def decoded(b: bytes, encoding: str) -> Any:
    try:
        return b.decode(encoding)
    except UnicodeDecodeError as e:
        return e


def codec_inputs() -> Iterator[bytes]:
    pieces = [b"", b"a", b"\x00", b"\x7f", b"\x80", b"\xbf", b"\xc0", b"\xc1", b"\xc2", b"\xdf", b"\xe0", b"\xe1",
              b"\xed", b"\xee", b"\xef", b"\xf0", b"\xf4", b"\xf5", b"\xff", b"\xfe", b"\xa0", b"\x9f", b"\x8f",
              b"\x90", b"\xd8", b"\xdb", b"\xdc", b"\xdf"]
    for a in pieces:
        for b in pieces:
            yield a + b
            for c in (b"", b"\x80", b"\xbf", b"A"):
                yield a + b + c
    for bom in (b"\xff\xfe", b"\xfe\xff", b""):
        for body in (b"", b"a", b"a\x00", b"\x00a", b"\x00\xd8", b"\xd8\x00", b"\x00\xdc", b"\xdc\x00",
                     b"\x00\xd8\x00\xdc", b"\xd8\x00\xdc\x00", b"\x00\xd8a\x00", b"\xd8\x00\x00a", b"\x00\xd8\x00",
                     b"=\xd8\x00\xde", b"\xd8=\xde\x00", b"\x00\xdc\x00\xd8"):
            yield bom + body
    rng = random.Random(SEED)
    for _ in range(3000):
        n = rng.randrange(0, 12)
        alphabet = rng.choice([range(256), [0x00, 0xd8, 0xdc, 0xdf, 0x41, 0xff, 0xfe], [0x80, 0xbf, 0xc2, 0xe0, 0xed, 0xf0, 0xf4, 0x41]])
        yield bytes(rng.choice(alphabet) for _ in range(n))
    yield "héllo \U0001f600".encode()
    yield "héllo \U0001f600".encode("utf-16")


def codec_cases() -> Iterator[tuple[list, Any]]:
    seen: set[bytes] = set()
    for b in codec_inputs():
        if b in seen:
            continue
        seen.add(b)
        yield [b], [decoded(b, "utf-8"), decoded(b, "utf-16")]


def main() -> None:
    require_oracle_python()
    cmap_dir = codegen_cmaps.ensure()
    rel_cmap_dir = cmap_dir.relative_to(cache_dir()).as_posix()
    # the adversarial corpus this module replays, as its generator writes it
    adv_structure.generate()
    state = process_state()
    write_cases(MODULE, "py_process", [([], state)])
    n = write_cases(MODULE, "codecs", codec_cases())
    print(f"{MODULE}: {n} codec cases", file=sys.stderr)
    n = write_cases(MODULE, "stages", stage_cases())
    if process_state() != state:
        raise RuntimeError("the process state changed while the traces ran in children")
    print(f"{MODULE}: {n} stage traces", file=sys.stderr)
    write_meta(MODULE, cmap_dir=rel_cmap_dir)


if __name__ == "__main__":
    main()
