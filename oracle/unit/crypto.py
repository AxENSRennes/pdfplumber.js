def ranges(pred):
    out, start = [], None
    for c in range(0x110000):
        if pred(chr(c)):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def gen_tables(rng):
    for name, pred in PREDICATES.items():
        yield [name], ranges(pred)


UCD = unicodedata.ucd_3_2_0


def char_pools():
    """Code points by kind, for random strings (sorted: deterministic)."""
    pools = {name: [] for name in ("comb", "decomp", "compat", "unassigned32", "jamo", "hangul", "cjkcompat")}
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        ch = chr(c)
        if unicodedata.combining(ch):
            pools["comb"].append(c)
        d = unicodedata.decomposition(ch)
        if d:
            if UCD.category(ch) == "Cn":
                pools["unassigned32"].append(c)
            elif d.startswith("<"):
                pools["compat"].append(c)
            else:
                pools["decomp"].append(c)
    pools["jamo"] = list(range(0x1100, 0x1113)) + list(range(0x1161, 0x1176)) + list(range(0x11A7, 0x11C3)) + [
        0x1113, 0x1176, 0x11C3, 0x115F, 0x1160]
    pools["hangul"] = [0xAC00, 0xAC01, 0xAC1B, 0xAC1C, 0xD7A3, 0xD7A4, 0xB098, 0xB0A0]
    pools["cjkcompat"] = [0xF951, 0x2F868, 0x2F874, 0x2F91F, 0x2F95F, 0x2F9BF, 0x2136A, 0x5F33, 0x43AB]
    pools["ascii"] = list(range(0x20, 0x7F)) + [0x00, 0x07]
    pools["latin"] = list(range(0xA0, 0x180))
    pools["any"] = None
    return pools


def rand_text(rng, pools, n):
    out = []
    for _ in range(n):
        kind = rng.choice(list(pools))
        if kind == "any":
            c = rng.randrange(0x110000)
            while 0xD800 <= c <= 0xDFFF:
                c = rng.randrange(0x110000)
        else:
            c = rng.choice(pools[kind])
        out.append(chr(c))
    return "".join(out)


def gen_nfkc(rng):
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        r = UCD.normalize("NFKC", chr(c))
        if r != chr(c):
            yield ["cp", c], r
    pools = char_pools()
    # sequences of a starter and combining marks (reordering, blocking,
    # successive compositions) and of jamo (Hangul composition)
    combining_heavy = {"comb": pools["comb"], "decomp": pools["decomp"], "ascii": pools["ascii"][:60],
                       "jamo": pools["jamo"]}
    for _ in range(6000):
        p = combining_heavy if rng.random() < 0.6 else pools
        s = rand_text(rng, p, rng.randint(1, 12))
        yield ["str", s], UCD.normalize("NFKC", s)
    yield ["str", ""], UCD.normalize("NFKC", "")


