def call(f, *args):
    try:
        return f(*args)
    except Exception as e:  # the exception is the expected result
        return e


def shown(b):
    """A byte result as written: the bytes, or their SHA-256 when long."""
    if isinstance(b, (bytes, bytearray)) and len(b) > SHOWN_BYTES:
        return ["sha256", hashlib.sha256(b).hexdigest()]
    return b


def rand_bytes(rng, n):
    return bytes(rng.getrandbits(8) for _ in range(n))


