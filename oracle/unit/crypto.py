def collect_refs(x, out, depth=0):
    if depth > 50:
        return
    if isinstance(x, PDFObjRef):
        out.append(x.objid)
    elif isinstance(x, (list, tuple)):
        for v in x:
            collect_refs(v, out, depth + 1)
    elif isinstance(x, dict):
        for v in x.values():
            collect_refs(v, out, depth + 1)
    elif isinstance(x, PDFStream):
        collect_refs(x.attrs, out, depth + 1)


def raw_document(path, password):
    """A document whose objects are read as stored (``decipher`` off)."""
    fp = open(path, "rb")
    doc = PDFDocument.__new__(PDFDocument)
    error = None
    try:
        doc.__init__(PDFParser(fp), password=password)
    except Exception as e:
        error = e
    if getattr(doc, "encryption", None) is None:
        fp.close()
        return None, None, error
    doc.decipher = None
    doc._cached_objs.clear()
    doc._parsed_objs.clear()
    return doc, fp, error


def strings_of(x, out, depth=0):
    if depth > 50:
        return
    if isinstance(x, bytes):
        out.append(x)
    elif isinstance(x, list):
        for v in x:
            strings_of(v, out, depth + 1)
    elif isinstance(x, dict):
        for v in x.values():
            strings_of(v, out, depth + 1)


def detached(x, depth=0):
    """``x`` with references unbound (as typed JSON writes them)."""
    if depth > 60:
        return None
    if isinstance(x, PDFObjRef):
        return PDFObjRef(None, x.objid)
    if isinstance(x, list):
        return [detached(v, depth + 1) for v in x]
    if isinstance(x, tuple):
        return tuple(detached(v, depth + 1) for v in x)
    if isinstance(x, dict):
        return {k: detached(v, depth + 1) for k, v in x.items()}
    if isinstance(x, PDFStream):
        s = PDFStream(detached(x.attrs, depth + 1), x.rawdata if x.rawdata is not None else b"")
        if x.objid is not None:
            s.set_objid(x.objid, x.genno)
        return s
    return x


def corpus_case(f, rng):
    password = f.password or ""
    doc, fp, error = raw_document(f.path, password)
    if doc is None:
        return None
    try:
        docid, param = doc.encryption
        # the referenced objects, as the handler resolves them (not deciphered)
        table = {}
        todo = []
        collect_refs([docid, param], todo)
        while todo and len(table) < 200:
            objid = todo.pop(0)
            if objid in table:
                continue
            try:
                obj = doc.getobj(objid)
            except PDFObjectNotFound:
                continue
            except Exception as e:
                obj = e
            table[objid] = obj
            if not isinstance(obj, Exception):
                collect_refs(obj, todo)
        items = []
        total = 0
        positions = {}
        for xref in doc.xrefs:
            for objid in xref.get_objids():
                if isinstance(objid, int) and objid not in positions:
                    try:
                        positions[objid] = xref.get_pos(objid)
                    except Exception:
                        pass
        for objid in sorted(positions):
            if len(items) >= ITEMS_PER_FILE or total >= BYTES_PER_FILE:
                break
            try:
                obj = doc.getobj(objid)
            except Exception:
                continue
            genno = positions[objid][2]
            if isinstance(obj, PDFStream):
                data = (obj.rawdata or b"")[:ITEM_BYTES]
                found = [(obj.objid, obj.genno, data, detached(obj.attrs))]
            else:
                strings = []
                strings_of(obj, strings)
                found = [(objid, genno, s[:ITEM_BYTES], None) for s in strings if s]
            for objid1, genno1, data, attrs in found:
                if len(items) >= ITEMS_PER_FILE or total >= BYTES_PER_FILE:
                    break
                items.append([objid1, genno1, data, attrs, None])
                total += len(data)
    finally:
        fp.close()
    passwords = [password, "", "wrong-password", password + "x", "owner"]
    method_args = [["authenticate", pw] for pw in passwords]
    for pw in passwords:
        b = pw.encode("latin1", "replace")
        method_args += [["user", b], ["owner", b], ["key", b]]
    docid_d, param_d = detached(docid), detached(param)
    table_d = {k: detached(v) for k, v in table.items()}
    out = run_handler_case(docid_d, param_d, table_d, passwords, items, method_args)
    # PDFDocument's own outcome with the known password, for the record
    return [f.rel, canon(error), docid_d, param_d, sorted(table_d.items()), passwords, items, method_args], out


def gen_corpus(rng):
    for f in load_set("all"):
        if b"/Encrypt" not in f.path.read_bytes():
            continue
        case = corpus_case(f, rng)
        if case is not None:
            yield case


