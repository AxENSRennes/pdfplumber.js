def gen_arcfour(rng):
    for n in list(range(0, 20)) + [255, 256, 257, 300]:
        for _ in range(8):
            key = rand_bytes(rng, n)
            chunks = [rand_bytes(rng, rng.choice([0, 1, 5, 16, 100, 600])) for _ in range(rng.randint(1, 4))]

            def run(key=key, chunks=chunks):
                a = Arcfour(key)
                return [a.process(c) for c in chunks]

            yield [key, chunks], call(run)


def gen_unpad(rng):
    fixed = [b"", b"\x00", b"\x01", b"\x10", b"\x11", b"\x00" * 5, b"\x00" * 16, b"a\x00", b"\x10" * 16, b"\x10" * 15,
             b"x" * 15 + b"\x01", b"x" * 14 + b"\x02\x02", b"x" * 14 + b"\x01\x02", b"\x05" * 4, b"\x05" * 5,
             b"\x11" * 17, b"\xff", b"abc\x03\x03\x03", b"abc\x04\x03\x03\x03"]
    for b in fixed:
        yield [b], call(unpad_aes, b)
    for _ in range(3000):
        n = rng.choice([0, 1, 2, 15, 16, 17, 31, 32, 33, 48]) if rng.random() < 0.5 else rng.randint(0, 64)
        body = rand_bytes(rng, n)
        r = rng.random()
        if r < 0.3 and n:
            p = rng.randint(1, min(n, 17))
            body = body[: n - p] + bytes([p]) * p
        elif r < 0.45 and n:
            p = rng.randint(1, min(n, 16))
            tail = bytearray([p]) * p
            tail[rng.randrange(p)] = rng.choice([0, p + 1, 255])
            tail[-1] = p
            body = body[: n - p] + bytes(tail)
        elif r < 0.55:
            body = b"\x00" * n if rng.random() < 0.5 else body[:-1] + b"\x00" if n else b""
        elif r < 0.7 and n:
            body = body[:-1] + bytes([rng.randint(0, 20)])
        yield [body], call(unpad_aes, body)


