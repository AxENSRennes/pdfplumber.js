def bind_refs(x, doc, depth=0):
    """``x`` with its references bound to ``doc`` (new containers)."""
    if isinstance(x, PDFObjRef):
        return PDFObjRef(doc, x.objid)
    if isinstance(x, list):
        return [bind_refs(v, doc, depth + 1) for v in x]
    if isinstance(x, tuple):
        return tuple(bind_refs(v, doc, depth + 1) for v in x)
    if isinstance(x, dict):
        return {k: bind_refs(v, doc, depth + 1) for k, v in x.items()}
    if isinstance(x, PDFStream):
        s = PDFStream(bind_refs(x.attrs, doc, depth + 1), x.rawdata)
        if x.objid is not None:
            s.set_objid(x.objid, x.genno)
        return s
    return x


def describe(h):
    """The attributes of a constructed handler."""
    d = {"class": type(h).__name__, "v": h.v, "r": h.r, "p": h.p, "o": h.o, "u": h.u, "length": h.length,
         "key": h.key, "printable": h.is_printable(), "modifiable": h.is_modifiable(),
         "extractable": h.is_extractable()}
    if isinstance(h, PDFStandardSecurityHandlerV4):
        d.update({"stmf": h.stmf, "strf": h.strf, "encrypt_metadata": h.encrypt_metadata,
                  "cfm": [[k, f.__name__] for k, f in h.cfm.items()]})
    if isinstance(h, PDFStandardSecurityHandlerV5):
        d.update({"oe": h.oe, "ue": h.ue, "o_hash": h.o_hash, "o_validation_salt": h.o_validation_salt,
                  "o_key_salt": h.o_key_salt, "u_hash": h.u_hash, "u_validation_salt": h.u_validation_salt,
                  "u_key_salt": h.u_key_salt})
    return d


def factory_of(param):
    """``_initialize_password``'s choice of class (``None``: unknown /V)."""
    v = int_value(param.get("V", 0))
    return PDFDocument.security_handler_registry.get(v)


def run_decrypt(h, item):
    objid, genno, data, attrs, name = item
    if name is None:
        out = call(h.decrypt, objid, genno, data, attrs)
    else:
        out = call(h.decrypt, objid, genno, data, attrs, name)
    return shown(out)


def run_handler_case(docid, param, table, passwords, items, method_args):
    """The output of a case (see the module documentation)."""
    doc = TableDoc({})
    doc.table = {k: bind_refs(v, doc) for k, v in table.items()}
    factory = factory_of(bind_refs(param, doc))
    out = []
    handler = None
    for pw in passwords:
        if factory is None:
            out.append(None)
            continue
        h = call(factory, bind_refs(docid, doc), bind_refs(param, doc), pw)
        if isinstance(h, Exception):
            out.append(h)
        else:
            out.append(describe(h))
            handler = handler or h
    if handler is None:
        return [out, None]
    h = handler
    extra = []
    for kind, arg in method_args:
        if kind == "authenticate":
            extra.append(call(h.authenticate, arg))
        elif kind == "user":
            extra.append(call(h.authenticate_user_password, arg))
        elif kind == "owner":
            extra.append(call(h.authenticate_owner_password, arg))
        elif kind == "compute_u":
            extra.append(call(h.compute_u, arg))
        elif kind == "key":
            extra.append(call(h.compute_encryption_key, arg))
    return [out, extra, [run_decrypt(h, item) for item in items]]


def aes_items(rng, h, aes256):
    """Items whose AES data decrypts to chosen plaintexts (valid, invalid
    and zero padding)."""
    items = []
    for _ in range(rng.randint(2, 6)):
        objid, genno = rng.choice([(1, 0), (7, 0), (12, 3), (2**24 + 5, 65535), (300, 1)])
        if aes256:
            key = h.key
        else:
            k = h.key + struct.pack("<L", objid)[:3] + struct.pack("<L", genno)[:2] + b"sAlT"
            key = hashlib.md5(k).digest()[: min(len(k), 16)]
        if len(key) not in (16, 24, 32):
            continue
        n = rng.choice([0, 1, 5, 15, 16, 17, 31, 32, 40])
        plain = rand_bytes(rng, n)
        r = rng.random()
        if r < 0.5:
            p = 16 - n % 16
            plain += bytes([p]) * p
        elif r < 0.65:
            plain += bytes(16 - n % 16)
        elif r < 0.8:
            p = 16 - n % 16
            plain += bytes([p]) * (p - 1) + bytes([rng.randint(1, 16)])
        else:
            plain += rand_bytes(rng, 16 - n % 16)
        iv = rand_bytes(rng, 16)
        data = iv + aes_cbc(key, iv, plain)
        if rng.random() < 0.2:
            data = data[: rng.randint(0, len(data))]
        items.append([objid, genno, data, None, None])
    return items


