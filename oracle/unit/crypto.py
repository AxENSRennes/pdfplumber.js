def gen_saslprep(rng):
    fixed = ["", "­", "I­X", "user", "Ⅸ", "\u0007", "ا1", "ا1ب",
             "اaب", "aا", "ȡ", "ª", "x y", "א", "\U0001f600", "ﬁ", "̀"]
    for s in fixed:
        for flag in (True, False):
            yield [s, flag], call(saslprep, s, flag)
    kinds = sorted(SASL_POOLS)
    for _ in range(5000):
        n = rng.randint(1, 8)
        weights = rng.sample(kinds, rng.randint(1, 4))
        s = "".join(chr(rng.choice(SASL_POOLS[rng.choice(weights)])) for _ in range(n))
        flag = rng.random() < 0.8
        yield [s, flag], call(saslprep, s, flag)


# -- security handlers ----------------------------------------------------------


class TableDoc:
    """A document whose getobj() reads a table (references in a case)."""

    def __init__(self, table):
        self.table = table

    def getobj(self, objid):
        if objid in self.table:
            obj = self.table[objid]
            if isinstance(obj, Exception):
                raise obj
            return obj
        raise PDFObjectNotFound(objid)


def bare(cls, **attrs):
    """A handler object without ``__init__``, for building inputs."""
    h = cls.__new__(cls)
    h.__dict__.update(attrs)
    return h


def xor_key(key, i):
    return bytes(c ^ i for c in key)


def make_o(owner, user, r, length):
    """Algorithm 3.3 as pdfminer reads it (authenticate_owner_password)."""
    h = hashlib.md5((owner + PAD)[:32]).digest()
    if r >= 3:
        for _ in range(50):
            h = hashlib.md5(h).digest()
    n = 5 if r == 2 else length // 8
    key = h[:n]
    o = Arcfour(key).encrypt((user + PAD)[:32])
    if r >= 3:
        for i in range(1, 20):
            o = Arcfour(xor_key(key, i)).encrypt(o)
    return o


def aes_cbc(key, iv, data, encrypt=True):
    c = Cipher(algorithms.AES(key), modes.CBC(iv))
    ctx = c.encryptor() if encrypt else c.decryptor()
    return ctx.update(data) + ctx.finalize()


def pdf_string_password(rng):
    return rng.choice(["user", "owner", "", "secret", "æøå", "x" * 40, "\xff\x00", "pw "])


def build_r234(rng, r, v, length, user, owner, docid, p, encrypt_metadata, cf_kind):
    o = make_o(owner.encode("latin1"), user.encode("latin1"), r, length)
    param = {"Filter": LIT("Standard"), "V": v, "R": r, "O": o, "U": b"", "P": p}
    if v in (2, 3) or rng.random() < 0.3:
        param["Length"] = length
    if v == 4:
        param["CF"] = {"StdCF": {"CFM": LIT(cf_kind), "AuthEvent": LIT("DocOpen"), "Length": 16}}
        param["StmF"] = LIT("StdCF")
        param["StrF"] = LIT("StdCF")
        if encrypt_metadata is not None:
            param["EncryptMetadata"] = encrypt_metadata
    h = bare(PDFStandardSecurityHandlerV4, r=r, o=o, p=p if p > 0 else p + 2**32, docid=docid, length=length,
             encrypt_metadata=bool(param.get("EncryptMetadata", True)))
    key = h.compute_encryption_key(user.encode("latin1"))
    param["U"] = h.compute_u(key)
    return param


def build_r56(rng, r, user, owner, p, encrypt_metadata):
    h = bare(PDFStandardSecurityHandlerV5, r=r)
    file_key = rand_bytes(rng, 32)
    uv, uk, ov, ok = (rand_bytes(rng, 8) for _ in range(4))
    ub, ob = h._normalize_password(user), h._normalize_password(owner)
    u = h._password_hash(ub, uv) + uv + uk
    ue = aes_cbc(h._password_hash(ub, uk), b"\0" * 16, file_key)
    o = h._password_hash(ob, ov, u) + ov + ok
    oe = aes_cbc(h._password_hash(ob, ok, u), b"\0" * 16, file_key)
    param = {"Filter": LIT("Standard"), "V": 5, "R": r, "O": o, "U": u, "OE": oe, "UE": ue, "P": p, "Length": 256,
             "CF": {"StdCF": {"CFM": LIT("AESV3"), "AuthEvent": LIT("DocOpen"), "Length": 32}},
             "StmF": LIT("StdCF"), "StrF": LIT("StdCF")}
    if encrypt_metadata is not None:
        param["EncryptMetadata"] = encrypt_metadata
    return param


