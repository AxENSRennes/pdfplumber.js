"""Differential cases for the encryption code of pdfminer: arcfour.py
(crates/pdfminer/src/arcfour.rs), _saslprep.py (saslprep.rs, with the
``unicodedata.ucd_3_2_0`` normalization it calls), utils.unpad_aes and the
security handlers of pdfdocument.py (pdfdocument/security.rs).

Writes typed JSON lines (docs/verification.md) to
``<cache>/unit/crypto/<fingerprint>/<name>.jsonl`` (``oracle/unit/_common.py``),
``{"in": [...], "out": ...}``; the Rust replay is
crates/pdftrace/tests/crypto_unit.rs.

- ``arcfour``: ``Arcfour(key)`` then ``process`` on several chunks (the key
  stream continues), for random keys of 0 to 300 bytes.
- ``unpad``: ``unpad_aes`` on padded, mispadded, zero-ended and short data.
- ``tables``: the ranges of every ``stringprep.in_table_*`` predicate
  ``saslprep`` uses, re-derived here (the Rust tables are generated by
  ``oracle/codegen/saslprep_tables.py``).
- ``nfkc``: ``unicodedata.ucd_3_2_0.normalize("NFKC", s)``: every code point
  the normalization changes (``["cp", c]``; the Rust test checks that all the
  others are unchanged), and random strings of combining marks, Hangul jamo,
  compatibility characters, characters unassigned in Unicode 3.2.0 and
  the normalization corrections.
- ``saslprep``: ``saslprep(s, prohibit_unassigned)`` on random strings mixing
  every table (mapped to nothing, spaces, prohibited, bidirectional,
  unassigned), with the exception when a check fails.
- ``handlers``: generated encryption dictionaries for every revision (2 to 6)
  and ``/V`` (0 to 6), with consistent ``/O``, ``/U``, ``/OE``, ``/UE`` for
  a user and an owner password, then varied: ``/Length``, ``/P``, ``/ID``,
  ``/CF`` (``V2``, ``AESV2``, ``AESV3``, unknown, missing, not a dict),
  ``/StmF``/``/StrF`` (``Identity``, undefined, mismatched),
  ``/EncryptMetadata``, missing or mistyped entries, indirect references. A
  case is ``[docid, param, table, passwords, items]``: the handler class is
  picked by ``PDFDocument.security_handler_registry`` from ``/V`` (as
  ``_initialize_password``), constructed with each password (``describe``),
  and the first handler that authenticates runs ``authenticate``,
  ``authenticate_user_password``/``authenticate_owner_password``,
  ``compute_u``, ``compute_encryption_key`` and ``decrypt`` on the items
  (``[objid, genno, data, attrs, name]``: AES data built with valid, invalid
  and zero padding, partial blocks, out-of-range object numbers,
  ``/Type /Metadata`` dictionaries, crypt filter names).
- ``corpus``: every PDF of the set ``all`` whose trailer has ``/Encrypt``:
  ``doc.encryption`` read by ``PDFDocument`` (opened with its known
  password), the handler built with the right, empty and wrong passwords,
  and ``decrypt`` of the strings and stream data of its objects (read with
  ``decipher`` disabled: the stored bytes), at most ``ITEMS_PER_FILE`` items
  and ``BYTES_PER_FILE`` bytes per file, each item cut at ``ITEM_BYTES``.
- ``deep``: ``decipher_all(handler.decrypt, ...)`` on lists nested around the
  Python frame limit, called at a measured depth (``_common.at_depth``), for
  each decryption path (RC4, AES-128, AES-256, Identity, padding checked or
  not, key or IV errors): the frames of ``decrypt``, ``unpad_aes`` and of
  ``cryptography``'s Python layer.

In the inputs, ``{"ref": n}`` is a reference to the case's ``table`` (a list
of ``[objid, object]``; a missing id raises ``PDFObjectNotFound``, so the
reference resolves to ``None``). Byte results longer than ``SHOWN_BYTES`` are
given as ``["sha256", hex]``.

Usage: PDFPLUMBER_ROOT=<main checkout> <root>/.venv/bin/python -m oracle.unit.crypto
"""

