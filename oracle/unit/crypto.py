def deep_handlers(rng):
    """Handlers of every decryption path, as ``(name, docid, param, password)``."""
    docid = [b"0123456789abcdef", b"fedcba9876543210"]
    specs = []
    for v, r, length, cf in [(1, 2, 40, None), (2, 3, 128, None), (4, 4, 128, "V2"), (4, 4, 128, "AESV2")]:
        metadata = False if v == 4 else None
        param = build_r234(rng, r, v, length, "user", "owner", docid, -4, metadata, cf or "V2")
        specs.append((f"v{v}r{r}{cf or ''}", docid, param, "user"))
        if v == 4:
            ident = dict(param, StmF=LIT("Identity"), StrF=LIT("Identity"))
            specs.append(("identity", docid, ident, "user"))
    param = build_r56(rng, 6, "user", "owner", -4, False)
    specs.append(("v5r6", docid, param, "user"))
    bad = dict(param, UE=param["UE"] + bytes(16))  # a 48-byte key: AES raises
    specs.append(("v5bad", docid, bad, "user"))
    return specs


def deep_leaves(rng, h):
    leaves = [b"x" * 5, b"y" * 40]
    if isinstance(h, PDFStandardSecurityHandlerV4):
        leaves += [b"\x01" * 3, bytes(48)]  # a short IV; zeros
        if h.key is not None and len(h.key) in (16, 32):
            key = h.key
            if not isinstance(h, PDFStandardSecurityHandlerV5):
                k = h.key + struct.pack("<L", 1)[:3] + struct.pack("<L", 0)[:2] + b"sAlT"
                key = hashlib.md5(k).digest()[:16]
            iv = bytes(range(16))
            leaves.append(iv + aes_cbc(key, iv, b"hello" + bytes([11]) * 11))  # padding checked: removed
            leaves.append(iv + aes_cbc(key, iv, b"hello" + bytes([11]) * 10 + b"\x05"))  # padding checked: kept
            leaves.append(iv + aes_cbc(key, iv, b"hello" + bytes([11]) * 10 + b"\xf0"))  # not checked
    return leaves


def canon_sha(x):
    if isinstance(x, BaseException):
        return x
    return hashlib.sha256(canon(x).encode("ascii")).hexdigest()


DEEP_ATTRS = [None, {"Type": LIT("Metadata")}, {"Type": LIT("XRef")}]


def gen_deep(rng):
    for name, docid, param, password in deep_handlers(rng):
        h = factory_of(param)(docid, param, password)
        for attrs in DEEP_ATTRS:
            if attrs is None:
                decrypt = h.decrypt
            else:
                # a stream's dictionary, through a function of one frame
                def decrypt(objid, genno, data, _attrs=None, attrs=attrs):
                    return h.decrypt(objid, genno, data, attrs)

            for leaf in deep_leaves(rng, h):
                # warm cryptography's isinstance caches as a document does
                call(decipher_all, decrypt, 1, 0, [leaf])
                frames = depth_here()["py"] + 1  # at_depth's frame
                for n in range(1000 - frames - 12, 1000 - frames + 2):
                    depth, out = at_depth(decipher_all, decrypt, 1, 0, nested_list(n, leaf))
                    yield [name, docid, param, password, attrs, depth, n, leaf], canon_sha(out)


