"""Generate the PostScript symbols a Python process has interned before it
runs pdfminer: those its imports intern (module constants such as
``LITERAL_PAGES = LIT("Pages")``).

    PDFPLUMBER_ROOT=<main checkout> <root>/.venv/bin/python oracle/codegen/py_symbols.py [--check]

Interning a name for the first time in a process instantiates the symbol
(``PSSymbolTable.intern`` calls ``PSLiteral.__init__``), a Python frame more
than for a name already interned, which decides where a ``RecursionError``
happens in a deep recursion (``docs/architecture.md``, "Profondeur de
récursion"; ``pdfminer::psparser::py_intern``). So the port needs the names
the process starts with:

- ``crates/pdfminer/src/psparser_symbols.rs``: after ``import pdfplumber``,
  the process of a pdfplumber user (the default of the port);
- ``crates/pdftrace/src/stages/py_symbols.rs``: for each stage of
  ``oracle/stages/``, after the imports of ``python -m oracle.trace --stage
  S`` (``oracle.trace`` and the stage module), the process in which the
  oracle computes every trace (``oracle/cache.py``).

Each set is read from a fresh interpreter. ``--check`` exits 1 if a file is
not what this script generates (``scripts/check.sh`` runs it).
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PDFMINER_OUT = REPO / "crates" / "pdfminer" / "src" / "psparser_symbols.rs"
STAGES_OUT = REPO / "crates" / "pdftrace" / "src" / "stages" / "py_symbols.rs"

DUMP = """
import json, sys
{imports}
from pdfminer.psparser import PSKeywordTable, PSLiteralTable
lits = [[isinstance(k, bytes), k.hex() if isinstance(k, bytes) else k] for k in PSLiteralTable.dict]
kwds = [k.hex() for k in PSKeywordTable.dict]
json.dump({{"literals": lits, "keywords": kwds}}, sys.stdout)
"""


def interned(imports: str) -> dict:
    out = subprocess.run(
        [sys.executable, "-c", DUMP.format(imports=imports)],
        cwd=REPO,
        env={**os.environ, "PYTHONPATH": str(REPO)},
        capture_output=True,
        check=True,
        timeout=120,
    )
    return json.loads(out.stdout)


def stage_names() -> list[str]:
    return sorted(p.stem for p in (REPO / "oracle" / "stages").glob("*.py") if not p.stem.startswith("_"))


def rust_bytes(hexs: str) -> str:
    out = ['b"']
    for c in bytes.fromhex(hexs):
        if 0x20 <= c < 0x7F and c not in b'"\\':
            out.append(chr(c))
        else:
            out.append(f"\\x{c:02x}")
    out.append('"')
    return "".join(out)


def rust_str(s: str) -> str:
    out = ['"']
    for ch in s:
        c = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 0x20 <= c < 0x7F:
            out.append(ch)
        else:
            out.append(f"\\u{{{c:x}}}")
    out.append('"')
    return "".join(out)


def symbols_expr(table: dict, indent: str) -> str:
    """A ``Symbols`` value (sorted, so the file does not depend on the
    order of interning)."""
    strs = sorted(k for is_bytes, k in table["literals"] if not is_bytes)
    byts = sorted(k for is_bytes, k in table["literals"] if is_bytes)
    kwds = sorted(table["keywords"])
    lines = [f"{indent}Symbols {{"]
    lines.append(f"{indent}    literals: &[{', '.join(rust_str(s) for s in strs)}],")
    lines.append(f"{indent}    bytes_literals: &[{', '.join(rust_bytes(b) for b in byts)}],")
    lines.append(f"{indent}    keywords: &[{', '.join(rust_bytes(k) for k in kwds)}],")
    lines.append(f"{indent}}}")
    return "\n".join(lines)


HEADER = "// Generated by oracle/codegen/py_symbols.py: do not edit.\n"


def pdfminer_file() -> str:
    table = interned("import pdfplumber")
    return (
        HEADER
        + "//! The symbols a Python process has interned after `import pdfplumber`\n"
        + "//! (see `psparser::py_intern`).\n\n"
        + "use crate::psparser::Symbols;\n\n"
        + "/// The symbols interned by `import pdfplumber`.\n"
        + "pub const IMPORT_PDFPLUMBER: Symbols = "
        + symbols_expr(table, "").lstrip()
        + ";\n"
    )


def stages_file() -> str:
    arms = []
    for stage in stage_names():
        table = interned(f"import oracle.trace\nfrom oracle.stages import get_stage\nget_stage({stage!r})")
        arms.append(f"        {rust_str(stage)} => Some(\n{symbols_expr(table, '            ')},\n        ),")
    return (
        HEADER
        + "//! The symbols interned in the process where the oracle computes a trace\n"
        + "//! of each stage (`python -m oracle.trace --stage S`), before it runs.\n\n"
        + "use pdfminer::psparser::Symbols;\n\n"
        + "/// The symbols of the oracle's process for stage `stage`.\n"
        + "pub fn for_stage(stage: &str) -> Option<Symbols> {\n"
        + "    match stage {\n"
        + "\n".join(arms)
        + "\n        _ => None,\n    }\n}\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for path, text in ((PDFMINER_OUT, pdfminer_file()), (STAGES_OUT, stages_file())):
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f"{path.relative_to(REPO)} is not what oracle/codegen/py_symbols.py generates", file=sys.stderr)
                bad = 1
        else:
            path.write_text(text)
    return bad


if __name__ == "__main__":
    sys.exit(main())
