"""Generate the option tables of the ``plumber_*`` stages for their Rust
side: ``crates/pdftrace/src/stages/plumber_ops.rs``, and for the harness
that writes them through the public JavaScript API:
``js/trace/plumber-ops.json`` (``{"constants": {...}, "tables": {name:
typed JSON}}``, the same names).

    PDFPLUMBER_ROOT=<main checkout> <root>/.venv/bin/python oracle/codegen/plumber_ops.py [--check]

The stages ``oracle/stages/plumber_text.py``, ``plumber_tables.py`` and
``plumber_doc.py`` run the ops, derivations, settings and ``open`` options
of their tables (a slice per page, ``plumber_objects.select``). The Rust
stages must run the same ones: each table is written as the typed JSON
text (``oracle/typed_json.py``, ``crates/pdftrace/src/typed_json.rs``) of
the Python value, which the Rust side decodes (``typed_json::parse``),
together with the integer constants. ``--check`` exits 1 if the file is
not what this script generates (``scripts/check.sh`` runs it).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from oracle import typed_json  # noqa: E402
from oracle.stages import plumber_doc, plumber_tables, plumber_text  # noqa: E402

OUT = REPO / "crates" / "pdftrace" / "src" / "stages" / "plumber_ops.rs"
OUT_JS = REPO / "js" / "trace" / "plumber-ops.json"

#: (Rust name, module, attribute): typed JSON tables
TABLES = [
    ("TEXT_BASE_OPS", plumber_text, "BASE_OPS"),
    ("TEXT_VARIANT_OPS", plumber_text, "VARIANT_OPS"),
    ("TEXT_DERIVED", plumber_text, "DERIVED"),
    ("TEXT_DERIVED_OPS", plumber_text, "DERIVED_OPS"),
    ("TABLES_BASE_OPS", plumber_tables, "BASE_OPS"),
    ("TABLES_VARIANT_OPS", plumber_tables, "VARIANT_OPS"),
    ("TABLES_DERIVED_OPS", plumber_tables, "DERIVED_OPS"),
    ("DOC_DERIVED_BASE", plumber_doc, "DERIVED_BASE"),
    ("DOC_DERIVED", plumber_doc, "DERIVED"),
    ("DOC_SERIALIZE", plumber_doc, "SERIALIZE"),
    ("DOC_OPEN_OPTIONS", plumber_doc, "OPEN_OPTIONS"),
    ("DOC_WRONG_PASSWORD", plumber_doc, "WRONG_PASSWORD"),
]

#: (Rust name, module, attribute): usize constants
CONSTANTS = [
    ("OUT_LIMIT", plumber_text, "OUT_LIMIT"),
    ("TEXT_VARIANTS_PER_PAGE", plumber_text, "VARIANTS_PER_PAGE"),
    ("TEXT_DERIVED_PER_PAGE", plumber_text, "DERIVED_PER_PAGE"),
    ("TABLES_VARIANTS_PER_PAGE", plumber_tables, "VARIANTS_PER_PAGE"),
    ("DOC_DERIVED_PER_PAGE", plumber_doc, "DERIVED_PER_PAGE"),
    ("DOC_SERIALIZE_PER_PAGE", plumber_doc, "SERIALIZE_PER_PAGE"),
    ("DOC_MAX_ELEMENTS", plumber_doc, "MAX_ELEMENTS"),
    ("DOC_MAX_FOUND", plumber_doc, "MAX_FOUND"),
    ("DOC_MAX_PROBED", plumber_doc, "MAX_PROBED"),
    ("DOC_NORM_PAGES", plumber_doc, "NORM_PAGES"),
]

HEADER = """\
// @generated by oracle/codegen/plumber_ops.py from oracle/stages/plumber_*.py: do not edit.
//! The option tables of the `plumber_*` stages, as typed JSON texts
//! (`crate::typed_json::parse`) of the Python values, and their constants.
//! The stages pick a slice of each table per page with `select`
//! (`oracle/stages/plumber_objects.py`).

"""


def render() -> str:
    out = [HEADER]
    for name, module, attr in CONSTANTS:
        value = getattr(module, attr)
        assert isinstance(value, int) and value >= 0, (name, value)
        out.append(f"/// `{module.__name__.rsplit('.', 1)[1]}.{attr}`\npub const {name}: usize = {value};\n\n")
    for name, module, attr in TABLES:
        text = typed_json.dumps(getattr(module, attr))
        assert '"##' not in text, name
        out.append(f'/// `{module.__name__.rsplit(".", 1)[1]}.{attr}`\npub const {name}: &str = r##"{text}"##;\n\n')
    return "".join(out).rstrip("\n") + "\n"


def render_js() -> str:
    """``js/trace/plumber-ops.json``: the constants and the tables (typed JSON)."""
    constants = ",\n".join(f'    "{name}": {getattr(module, attr)}' for name, module, attr in CONSTANTS)
    tables = ",\n".join(f'    "{name}": {typed_json.dumps(getattr(module, attr))}' for name, module, attr in TABLES)
    return (
        '{\n  "generated": "by oracle/codegen/plumber_ops.py from oracle/stages/plumber_*.py: do not edit",\n'
        f'  "constants": {{\n{constants}\n  }},\n  "tables": {{\n{tables}\n  }}\n}}\n'
    )


def main() -> int:
    ap = argparse.ArgumentParser(prog="oracle/codegen/plumber_ops.py", description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    outputs = [(OUT, render()), (OUT_JS, render_js())]
    if args.check:
        stale = [path for path, text in outputs if not path.exists() or path.read_text() != text]
        for path in stale:
            print(f"{path.relative_to(REPO)} is not what oracle/codegen/plumber_ops.py generates", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs:
        path.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
