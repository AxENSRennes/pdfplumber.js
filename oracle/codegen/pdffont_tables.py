"""Generate the data tables of ``pdfminer/pdffont.py`` from the oracle's pdfminer.

    PDFPLUMBER_ROOT=<main checkout> <root>/.venv/bin/python oracle/codegen/pdffont_tables.py [--check]

writes ``crates/pdfminer/src/pdffont/tables.rs``: ``NIBBLES`` and
``CFFFont.STANDARD_STRINGS``, read from the imported module (never copied by
hand, ``docs/architecture.md``, "Données upstream"), with their ``file:line``
references. ``--check`` exits 1 if the file is not what this script generates
(``scripts/check.sh`` runs it).
"""

from __future__ import annotations

import argparse
import ast
import inspect
import sys
from pathlib import Path

import pdfminer
from pdfminer import pdffont

sys.path.insert(0, str(Path(__file__).resolve().parent))
from pdfminer_tables import line_of, rust_str  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "crates" / "pdfminer" / "src" / "pdffont" / "tables.rs"


def class_attr_line(cls, name: str) -> int:
    """The line of the assignment of ``name`` in the body of ``cls``."""
    source, first = inspect.getsourcelines(cls)
    tree = ast.parse("".join(source))
    (node,) = tree.body
    for stmt in node.body:
        if isinstance(stmt, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in stmt.targets):
            return first + stmt.lineno - 1
    raise LookupError(f"{cls.__name__}.{name}")


def render() -> str:
    nibbles = pdffont.NIBBLES
    strings = pdffont.CFFFont.STANDARD_STRINGS
    assert all(type(s) is str for s in strings)
    nibble_items = ", ".join("None" if n is None else f"Some({rust_str(n)})" for n in nibbles)
    rows = "\n".join(f"    {rust_str(s)}," for s in strings)
    return (
        "//! Tables of `pdfminer/pdffont.py`: generated by `oracle/codegen/pdffont_tables.py`\n"
        f"//! from pdfminer.six {pdfminer.__version__} (the oracle's). Do not edit.\n\n"
        f"// pdfminer/pdffont.py:{line_of(pdffont, 'NIBBLES')} NIBBLES\n"
        "/// The characters of the nibbles of a real number in a CFF DICT (`None`:\n"
        "/// reserved).\n"
        "#[rustfmt::skip]\n"
        f"pub static NIBBLES: [Option<&str>; {len(nibbles)}] = [{nibble_items}];\n\n"
        f"// pdfminer/pdffont.py:{class_attr_line(pdffont.CFFFont, 'STANDARD_STRINGS')} CFFFont.STANDARD_STRINGS\n"
        "/// The standard strings of CFF (SIDs below their count).\n"
        "#[rustfmt::skip]\n"
        f"pub static STANDARD_STRINGS: [&str; {len(strings)}] = [\n"
        f"{rows}\n"
        "];\n"
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the generated file is not up to date")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is not up to date: run python oracle/codegen/pdffont_tables.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
