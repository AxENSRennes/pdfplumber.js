"""Generate the data modules of the pdfminer port from the oracle's pdfminer.

    PDFPLUMBER_ROOT=<main checkout> <root>/.venv/bin/python oracle/codegen/pdfminer_tables.py [--check]

writes, from the modules the oracle imports (never copied by hand,
``docs/architecture.md``, "Upstream Data"):

- ``crates/pdfminer/src/glyphlist.rs``: ``glyphname2unicode`` (``pdfminer/glyphlist.py``);
- ``crates/pdfminer/src/latin_enc.rs``: ``ENCODING`` (``pdfminer/latin_enc.py``);
- ``crates/pdfminer/src/fontmetrics.rs``: ``FONT_METRICS`` (``pdfminer/fontmetrics.py``),
  aliases included (``FONT_METRICS["Arial"] is FONT_METRICS["Helvetica"]``:
  the Rust aliases point to the same static).

The values are read from the imported modules (the dicts as Python built
them: a duplicated key keeps its first position and its last value), the
``file:line`` references from the module sources. ``--check`` exits 1 if a
file is not what this script generates (``scripts/check.sh`` runs it).
The data statics carry ``#[rustfmt::skip]``: one entry per line, as written
here.
"""

from __future__ import annotations

import argparse
import ast
import inspect
import math
import sys
from pathlib import Path

import pdfminer
from pdfminer import fontmetrics, glyphlist, latin_enc

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "crates" / "pdfminer" / "src"


def rust_str(s: str) -> str:
    """A Rust string literal for ``s`` (ASCII, ``\\u{...}`` escapes)."""
    out = ['"']
    for ch in s:
        c = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 0x20 <= c < 0x7F:
            out.append(ch)
        elif 0xD800 <= c < 0xE000:
            raise ValueError(f"a surrogate in {s!r}: not a Rust &str")
        else:
            out.append(f"\\u{{{c:x}}}")
    out.append('"')
    return "".join(out)


def rust_f64(x: float) -> str:
    """A Rust literal that parses to exactly ``x`` (``repr`` round-trips)."""
    if not math.isfinite(x):
        raise ValueError(f"not a finite float: {x!r}")
    text = repr(x)
    if "e" in text and "." not in text.split("e")[0]:
        mantissa, exp = text.split("e")
        text = f"{mantissa}.0e{exp}"
    assert float(text) == x and math.copysign(1.0, float(text)) == math.copysign(1.0, x)
    return text


def rust_int(x: int) -> str:
    if type(x) is not int or not -(2**63) <= x < 2**63:
        raise ValueError(f"not an i64: {x!r}")
    return str(x)


def line_of(module, name: str) -> int:
    """The line of the module-level assignment of ``name``."""
    tree = ast.parse(inspect.getsource(module))
    for node in tree.body:
        targets = node.targets if isinstance(node, ast.Assign) else [node.target] if isinstance(node, ast.AnnAssign) else []
        if any(isinstance(t, ast.Name) and t.id == name for t in targets):
            return node.lineno
    raise LookupError(f"{module.__name__}.{name}")


def header(module: str) -> str:
    return (
        f"//! Port of `pdfminer/{module}.py`: generated by `oracle/codegen/pdfminer_tables.py`\n"
        f"//! from pdfminer.six {pdfminer.__version__} (the oracle's). Do not edit.\n"
    )


def render_glyphlist() -> str:
    table = glyphlist.glyphname2unicode
    line = line_of(glyphlist, "glyphname2unicode")
    rows = "\n".join(f"    ({rust_str(k)}, {rust_str(v)})," for k, v in table.items())
    return (
        header("glyphlist")
        + "//!\n"
        "//! Mappings from Adobe glyph names to Unicode characters (the Adobe Glyph\n"
        "//! List 2.0, see the upstream module for its license). `convert_glyphlist`,\n"
        "//! the upstream tool that wrote the table, is not ported.\n\n"
        "use std::sync::LazyLock;\n\n"
        "use rustc_hash::FxHashMap;\n\n"
        f"// pdfminer/glyphlist.py:{line} glyphname2unicode\n"
        "/// `glyphname2unicode` as `(name, text)` pairs, in the order of the dict.\n"
        "#[rustfmt::skip]\n"
        "pub static GLYPHNAME2UNICODE: &[(&str, &str)] = &[\n"
        f"{rows}\n"
        "];\n\n"
        f"// pdfminer/glyphlist.py:{line} glyphname2unicode\n"
        "/// `glyphname2unicode` as a dict.\n"
        "#[allow(non_upper_case_globals)]\n"
        "pub static glyphname2unicode: LazyLock<FxHashMap<&'static str, &'static str>> =\n"
        "    LazyLock::new(|| GLYPHNAME2UNICODE.iter().copied().collect());\n"
    )


def render_latin_enc() -> str:
    line = line_of(latin_enc, "ENCODING")
    type_line = line_of(latin_enc, "EncodingRow")

    def opt(x):
        return "None" if x is None else f"Some({rust_int(x)})"

    rows = []
    for row in latin_enc.ENCODING:
        name, *codes = row
        assert len(codes) == 4 and isinstance(name, str), row
        rows.append(f"    ({rust_str(name)}, {', '.join(opt(c) for c in codes)}),")
    return (
        header("latin_enc")
        + "//!\n"
        "//! Standard encoding tables used in PDF (PDF Reference 1.6, D.1 \"Latin\n"
        "//! Character Set and Encodings\").\n\n"
        f"// pdfminer/latin_enc.py:{type_line} EncodingRow\n"
        "/// `(name, std, mac, win, pdf)`.\n"
        "pub type EncodingRow = (&'static str, Option<i64>, Option<i64>, Option<i64>, Option<i64>);\n\n"
        f"// pdfminer/latin_enc.py:{line} ENCODING\n"
        "#[rustfmt::skip]\n"
        "pub static ENCODING: &[EncodingRow] = &[\n" + "\n".join(rows) + "\n];\n"
    )


def render_value(v) -> str:
    if isinstance(v, bool):
        raise ValueError(f"unexpected bool {v!r}")
    if isinstance(v, str):
        return f"FontMetricValue::Str({rust_str(v)})"
    if isinstance(v, int):
        return f"FontMetricValue::Int({rust_int(v)})"
    if isinstance(v, float):
        return f"FontMetricValue::Float({rust_f64(v)})"
    if isinstance(v, tuple) and all(type(x) is float for x in v):
        return f"FontMetricValue::FloatTuple(&[{', '.join(rust_f64(x) for x in v)}])"
    raise ValueError(f"unexpected font metric value {v!r}")


def render_fontmetrics() -> str:
    line = line_of(fontmetrics, "FONT_METRICS")
    metrics = fontmetrics.FONT_METRICS
    statics: dict[int, str] = {}  # id(tuple) -> static name
    parts = []
    for name, entry in metrics.items():
        if id(entry) in statics:
            continue
        static = "METRICS_" + "".join(c if c.isalnum() else "_" for c in name).upper()
        assert static not in statics.values(), static
        statics[id(entry)] = static
        props, widths = entry
        assert isinstance(props, dict) and isinstance(widths, dict), name
        prop_rows = "\n".join(f"        ({rust_str(k)}, {render_value(v)})," for k, v in props.items())
        width_rows = "\n".join(f"        ({rust_str(k)}, {rust_int(v)})," for k, v in widths.items())
        parts.append(
            "#[rustfmt::skip]\n"
            f"static {static}: FontMetrics = FontMetrics {{\n"
            "    descriptor: &[\n"
            f"{prop_rows}\n"
            "    ],\n"
            "    widths: &[\n"
            f"{width_rows}\n"
            "    ],\n"
            "};\n"
        )
    entries = "\n".join(f"    ({rust_str(name)}, &{statics[id(entry)]})," for name, entry in metrics.items())
    return (
        header("fontmetrics")
        + "//!\n"
        "//! Font metrics of the Adobe core 14 fonts (from their AFM files, see the\n"
        "//! upstream module for the license), and the aliases of implementation\n"
        "//! note 62 of the PDF Reference. `convert_font_metrics`, the upstream tool\n"
        "//! that wrote the table, is not ported.\n\n"
        "/// A value of a font descriptor: `str`, `int`, `float` or a tuple of floats\n"
        "/// (`FontBBox`).\n"
        "#[derive(Clone, Copy, Debug, PartialEq)]\n"
        "pub enum FontMetricValue {\n"
        "    Str(&'static str),\n"
        "    Int(i64),\n"
        "    Float(f64),\n"
        "    FloatTuple(&'static [f64]),\n"
        "}\n\n"
        "/// One entry of `FONT_METRICS`: `(descriptor, widths)`, both dicts, as\n"
        "/// `(key, value)` pairs in the order of the dict.\n"
        "#[derive(Debug)]\n"
        "pub struct FontMetrics {\n"
        "    pub descriptor: &'static [(&'static str, FontMetricValue)],\n"
        "    pub widths: &'static [(&'static str, i64)],\n"
        "}\n\n"
        f"// pdfminer/fontmetrics.py:{line} FONT_METRICS\n"
        "/// `FONT_METRICS` as `(name, metrics)` pairs in the order of the dict; an\n"
        "/// alias points to the same `FontMetrics` as its font (Python's `is`).\n"
        "#[rustfmt::skip]\n"
        "pub static FONT_METRICS: &[(&str, &FontMetrics)] = &[\n"
        f"{entries}\n"
        "];\n\n"
        f"// pdfminer/fontmetrics.py:{line} FONT_METRICS\n"
        "/// `FONT_METRICS.get(name)`.\n"
        "pub fn get(name: &str) -> Option<&'static FontMetrics> {\n"
        "    FONT_METRICS.iter().find(|(n, _)| *n == name).map(|(_, m)| *m)\n"
        "}\n\n" + "\n".join(parts)
    )


OUTPUTS = {
    "glyphlist.rs": render_glyphlist,
    "latin_enc.rs": render_latin_enc,
    "fontmetrics.rs": render_fontmetrics,
}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a generated file is not up to date")
    args = ap.parse_args(argv)
    stale = 0
    for name, render in OUTPUTS.items():
        path = SRC / name
        text = render()
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                print(f"{path} is not up to date: run python oracle/codegen/pdfminer_tables.py", file=sys.stderr)
                stale += 1
            continue
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO)}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
