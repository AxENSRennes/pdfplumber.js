"""Generate crates/pdfminer/src/ccitt_tables.rs: the code tables of pdfminer/ccitt.py.

``CCITTG4Parser`` builds its four parse trees (``MODE``, ``WHITE``,
``BLACK``, ``UNCOMPRESSED``) in its class body with
``BitParser.add(TABLE, value, bits)`` calls. This script reads those calls,
in order, from the upstream source the oracle runs
(``upstream/pdfminer-six/pdfminer/ccitt.py`` under ``PDFPLUMBER_ROOT``) and
writes them as Rust arrays that ``crates/pdfminer/src/ccitt.rs`` feeds to
the same ``BitParser.add``:

    python oracle/codegen/ccitt_tables.py [--check]

``--check`` exits 1 if the file is not up to date. ``oracle/unit/ccitt.py``
also compares the four trees built by the port with pdfminer's (``trees``
cases), so a wrong entry fails the unit replay.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "crates" / "pdfminer" / "src" / "ccitt_tables.rs"
TABLES = ("MODE", "WHITE", "BLACK", "UNCOMPRESSED")


def upstream_source() -> Path:
    sys.path.insert(0, str(REPO))
    from oracle.corpus import corpus_root  # noqa: PLC0415 - the repository package, after the path is set

    return corpus_root() / "upstream" / "pdfminer-six" / "pdfminer" / "ccitt.py"


def read_tables(source: str) -> dict[str, tuple[int, list[tuple[int | str, str]]]]:
    """``{table: (line of its assignment, [(value, bits), ...])}``."""
    tree = ast.parse(source)
    (cls,) = [n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "CCITTG4Parser"]
    tables: dict[str, tuple[int, list[tuple[int | str, str]]]] = {}
    for stmt in cls.body:
        if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name) and stmt.target.id in TABLES:
            tables[stmt.target.id] = (stmt.lineno, [])
        elif isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Call):
            call = stmt.value
            func = call.func
            assert isinstance(func, ast.Attribute) and func.attr == "add", ast.dump(call)
            assert isinstance(func.value, ast.Name) and func.value.id == "BitParser", ast.dump(call)
            table, value, bits = call.args
            assert isinstance(table, ast.Name) and table.id in tables, ast.dump(call)
            v = ast.literal_eval(value)
            b = ast.literal_eval(bits)
            assert isinstance(v, (int, str)) and not isinstance(v, bool) and isinstance(b, str), ast.dump(call)
            tables[table.id][1].append((v, b))
    assert tuple(tables) == TABLES, tuple(tables)
    return tables


def render(tables: dict[str, tuple[int, list[tuple[int | str, str]]]]) -> str:
    out = [
        "//! The `BitParser.add(TABLE, value, bits)` calls of the class body of",
        "//! `CCITTG4Parser` (pdfminer/ccitt.py), in order.",
        "//!",
        "//! Generated by `oracle/codegen/ccitt_tables.py` from the upstream source: do",
        "//! not edit.",
        "",
        "use super::TableValue::{self, Int, Str};",
        "",
    ]
    for name, (line, entries) in tables.items():
        out.append(f"// pdfminer/ccitt.py:{line} CCITTG4Parser.{name}")
        out.append(f"pub(super) const {name}: &[(TableValue, &str)] = &[")
        for v, b in entries:
            value = f"Int({v})" if isinstance(v, int) else f'Str("{v}")'
            out.append(f'    ({value}, "{b}"),')
        out.append("];")
        out.append("")
    return "\n".join(out[:-1]) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(prog="python oracle/codegen/ccitt_tables.py")
    ap.add_argument("--check", action="store_true", help="exit 1 if the generated file is not up to date")
    args = ap.parse_args()
    text = render(read_tables(upstream_source().read_text(encoding="utf-8")))
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(REPO)} is not up to date: run python oracle/codegen/ccitt_tables.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
