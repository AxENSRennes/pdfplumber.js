"""Generate crates/pycompat/src/unicodedata_tables.rs: the data of
``unicodedata.normalize`` in the oracle's CPython (Unicode 15.0).

CPython's ``Modules/unicodedata.c`` normalizes with ``nfd_nfkd`` and
``nfc_nfkc`` over tables that ``Tools/unicode/makeunicodedata.py`` derives
from the UCD; ``crates/pycompat/src/unicodedata.rs`` ports those two
functions. The tables are read back from the running ``unicodedata`` (which
must be the oracle's, Python 3.12):

- the canonical combining class (``unicodedata.combining``), as runs;
- the decomposition of each code point (``unicodedata.decomposition``):
  compatibility or canonical, and its code points (Hangul syllables are
  decomposed by arithmetic and have none);
- the composition pairs ``(first, last) -> composite``: the canonical
  decompositions into two code points whose first is a starter, of the
  characters NFC keeps (``makeunicodedata.py`` leaves out the composition
  exclusions; a character that NFC does not keep is one of them). Each pair
  is checked to compose (``normalize("NFC", first + last) == composite``).

    python oracle/codegen/unicodedata_tables.py [--check]

``--check`` exits 1 if the file is not up to date.
"""

from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "crates" / "pycompat" / "src" / "unicodedata_tables.rs"


def combining_runs() -> list[tuple[int, int, int]]:
    runs: list[tuple[int, int, int]] = []
    for c in range(0x110000):
        ccc = unicodedata.combining(chr(c))
        if not ccc:
            continue
        if runs and runs[-1][1] == c - 1 and runs[-1][2] == ccc:
            runs[-1] = (runs[-1][0], c, ccc)
        else:
            runs.append((c, c, ccc))
    return runs


def decompositions() -> list[tuple[int, bool, list[int]]]:
    out = []
    for c in range(0x110000):
        d = unicodedata.decomposition(chr(c))
        if not d:
            continue
        parts = d.split()
        compat = parts[0].startswith("<")
        if compat:
            parts = parts[1:]
        out.append((c, compat, [int(p, 16) for p in parts]))
    return out


def composition_pairs() -> list[tuple[int, int, int]]:
    pairs = []
    for c in range(0x110000):
        d = unicodedata.decomposition(chr(c))
        if not d or d.startswith("<"):
            continue
        parts = [int(p, 16) for p in d.split()]
        if len(parts) != 2 or unicodedata.combining(chr(parts[0])) != 0:
            continue
        if unicodedata.normalize("NFC", chr(c)) != chr(c):
            continue  # a composition exclusion
        if unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) != chr(c):
            raise AssertionError(f"pair {parts} does not compose to U+{c:04X}")
        pairs.append((parts[0], parts[1], c))
    pairs.sort()
    return pairs


def render() -> str:
    runs = combining_runs()
    decomps = decompositions()
    pairs = composition_pairs()
    lines = [
        f"//! Generated by `oracle/codegen/unicodedata_tables.py` from CPython {sys.version.split()[0]}",
        f"//! (`unicodedata` {unicodedata.unidata_version}). Do not edit.",
        "",
        f'pub const UNIDATA_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
        "/// Runs `(first, last, class)` of the canonical combining class (`unicodedata.combining`).",
        "pub static COMBINING: &[(u32, u32, u8)] = &[",
        *(f"    (0x{a:04x}, 0x{b:04x}, {k})," for a, b, k in runs),
        "];",
        "",
        "/// `(code point, compatibility?, decomposition)` (`unicodedata.decomposition`), sorted.",
        "pub static DECOMPOSITION: &[(u32, bool, &[u32])] = &[",
        *(
            f"    (0x{c:04x}, {'true' if compat else 'false'}, &[{', '.join(f'0x{x:04x}' for x in parts)}]),"
            for c, compat, parts in decomps
        ),
        "];",
        "",
        "/// Canonical composition pairs `(first, last, composite)`, sorted by `(first, last)`.",
        "pub static COMPOSITION: &[(u32, u32, u32)] = &[",
        *(f"    (0x{a:04x}, 0x{b:04x}, 0x{c:04x})," for a, b, c in pairs),
        "];",
        "",
        "/// The code points that are the last of a composition pair (`nfc_last`), sorted.",
        "pub static COMPOSITION_LAST: &[u32] = &[",
        *(f"    0x{b:04x}," for b in sorted({b for _, b, _ in pairs})),
        "];",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the generated file is not up to date")
    args = ap.parse_args(argv)
    if sys.version_info[:2] != (3, 12):
        print("unicodedata_tables.py: run it with the oracle's Python 3.12", file=sys.stderr)
        return 2
    text = render()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(REPO)} is out of date: run python oracle/codegen/unicodedata_tables.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
