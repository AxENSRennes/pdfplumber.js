"""Generate crates/pycompat/src/atan2_tables.rs: the data of the oracle's atan2().

CPython's ``math.atan2`` (``m_atan2``) handles NaNs, infinities and zeros
itself, then calls the C library's ``atan2``. On the oracle (x86-64 glibc
2.39) that is the IBM Accurate Mathematical Library's
``__ieee754_atan2`` (``sysdeps/ieee754/dbl-64/e_atan2.c``), which
``crates/pycompat/src/libm.rs`` ports. Its constants (``atnat2.h``: the
polynomial ``d3``..``d13`` and the multiples of pi) and its table ``cij``
(``uatan.tbl``: 241 rows of ``x0`` and six polynomial coefficients) are read
here from the vendored glibc sources (``upstream/glibc``, see the README
there), from their big-endian variants (``{{high word, low word}}``), and
written as IEEE-754 bit patterns, so the Rust constants are exactly the C
ones:

    python oracle/codegen/atan2_tables.py [--check]

``--check`` exits 1 if the file is not up to date.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "upstream" / "glibc" / "sysdeps" / "ieee754" / "dbl-64"
OUT = REPO / "crates" / "pycompat" / "src" / "atan2_tables.rs"

#: The constants of atnat2.h that __ieee754_atan2 reads.
CONSTANTS = [
    "d3", "d5", "d7", "d9", "d11", "d13",
    "inv16", "opi", "opi1", "mopi", "hpi", "hpi1", "mhpi",
    "qpi", "mqpi", "tqpi", "mtqpi", "two500", "twom500",
]  # fmt: skip

_PAIR = r"\{\{\s*0[xX]([0-9a-fA-F]{8})\s*,\s*0[xX]([0-9a-fA-F]{8})\s*\}\s*\}"


def big_endian_section(text: str) -> str:
    """The ``#ifdef BIG_ENDI`` part of a glibc table file (words in
    ``{high, low}`` order)."""
    start = text.index("#ifdef BIG_ENDI")
    end = text.index("#else", start)
    return text[start:end]


def constants(path: Path) -> dict[str, int]:
    text = big_endian_section(path.read_text(encoding="utf-8"))
    out = {}
    for name in CONSTANTS:
        m = re.search(rf"\b{name}\s*=\s*{_PAIR}", text)
        if not m:
            raise ValueError(f"no constant {name} in {path}")
        out[name] = int(m.group(1), 16) << 32 | int(m.group(2), 16)
    return out


def cij(path: Path) -> list[list[int]]:
    text = big_endian_section(path.read_text(encoding="utf-8"))
    body = text[text.index("cij[241][7]") :]
    values = [int(hi, 16) << 32 | int(lo, 16) for hi, lo in re.findall(_PAIR, body)]
    if len(values) != 241 * 7:
        raise ValueError(f"cij: {len(values)} values, expected {241 * 7}")
    return [values[i : i + 7] for i in range(0, len(values), 7)]


def render(consts: dict[str, int], table: list[list[int]]) -> str:
    lines = [
        "// Generated by oracle/codegen/atan2_tables.py from",
        "// upstream/glibc/sysdeps/ieee754/dbl-64/{atnat2.h,uatan.tbl}; do not edit.",
        "// Values are IEEE-754 bit patterns (see crates/pycompat/src/libm.rs).",
        "",
    ]
    for name in CONSTANTS:
        lines.append(f"/// `{name}` of `atnat2.h`")
        lines.append(f"pub(crate) const ATAN2_{name.upper()}: u64 = 0x{consts[name]:016x};")
    lines.append("/// `cij` of `uatan.tbl`: `x0` then the coefficients `c1`..`c6` of each row")
    lines.append("pub(crate) const ATAN2_CIJ: [[u64; 7]; 241] = [")
    for row in table:
        lines.append("    [" + ", ".join(f"0x{v:016x}" for v in row) + "],")
    lines.append("];")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the generated file is not up to date")
    args = ap.parse_args(argv)
    text = render(constants(SRC / "atnat2.h"), cij(SRC / "uatan.tbl"))
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(REPO)} is out of date: run python oracle/codegen/atan2_tables.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
