"""Generate crates/pycompat/src/unicode_tables.rs from the running CPython.

The tables are the Unicode properties CPython uses in the code paths pycompat
reproduces (``str.isprintable`` for ``repr(str)``, ``str.isspace`` and the
decimal digit values for ``int(str)``/``float(str)``). They must come from the
oracle's Python (3.12, Unicode 15.0), so run:

    .venv/bin/python oracle/codegen/unicode_tables.py

``oracle/unit/pycompat.py`` re-derives the same ranges and the Rust tests
compare them, so a table generated by another Python version is caught.
"""

import os
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "crates", "pycompat", "src", "unicode_tables.rs")


def ranges(pred):
    out, start = [], None
    for c in range(0x110000):
        if pred(c):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def decimal_runs():
    """Runs (first, last, value of first) of consecutive decimal digits."""
    runs = []
    for c in range(0x110000):
        ch = chr(c)
        if not ch.isdecimal():
            continue
        value = unicodedata.decimal(ch)
        if runs and runs[-1][1] == c - 1 and runs[-1][2] + (c - runs[-1][0]) == value:
            runs[-1] = (runs[-1][0], c, runs[-1][2])
        else:
            runs.append((c, c, value))
    return runs


def table(name, rows, fmt):
    body = "\n".join("    " + fmt(r) + "," for r in rows)
    return f"pub static {name}: &[{'(u32, u32)' if len(rows[0]) == 2 else '(u32, u32, u32)'}] = &[\n{body}\n];\n"


def main():
    nonprintable = ranges(lambda c: not chr(c).isprintable())
    space = ranges(lambda c: chr(c).isspace())
    digits = decimal_runs()
    src = (
        "//! Generated by `oracle/codegen/unicode_tables.py` from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.\n\n"
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";\n\n'
        "/// Inclusive code point ranges where `str.isprintable()` is false.\n"
        + table("NONPRINTABLE", nonprintable, lambda r: f"(0x{r[0]:04x}, 0x{r[1]:04x})")
        + "\n/// Inclusive code point ranges where `str.isspace()` is true.\n"
        + table("SPACE", space, lambda r: f"(0x{r[0]:04x}, 0x{r[1]:04x})")
        + "\n/// Runs `(first, last, value of first)` of decimal digits (`str.isdecimal()`),\n"
        "/// whose values increase by one per code point.\n"
        + table("DECIMAL", digits, lambda r: f"(0x{r[0]:04x}, 0x{r[1]:04x}, {r[2]})")
    )
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(src)
    print(f"wrote {os.path.relpath(OUT)}: {len(nonprintable)} non-printable, {len(space)} space, {len(digits)} decimal runs")


if __name__ == "__main__":
    main()
