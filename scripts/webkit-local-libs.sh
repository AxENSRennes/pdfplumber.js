#!/usr/bin/env bash
# Makes Playwright's WebKit runnable on a Debian/Ubuntu machine without root
# (docs/js-runtime.md, "Navigateurs"): downloads the system libraries it
# lacks with `apt-get download` (no installation), extracts them under
# $PDFPLUMBER_ROOT/.cache/webkit-libs/root, and writes a launcher,
# .cache/webkit-libs/webkit.sh, that starts Playwright's MiniBrowser with
# them on LD_LIBRARY_PATH. js/playwright.config.ts uses the launcher when
# PDFPLUMBER_WEBKIT is set to its path (scripts/check-browsers.sh does).
#
#   scripts/webkit-local-libs.sh        # prints the launcher's path
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PDFPLUMBER_ROOT="${PDFPLUMBER_ROOT:-$ROOT}"
OUT="$PDFPLUMBER_ROOT/.cache/webkit-libs"
LIBDIR="$OUT/root/usr/lib/x86_64-linux-gnu"
WEBKIT="$(ls -d "${PLAYWRIGHT_BROWSERS_PATH:-$HOME/.cache/ms-playwright}"/webkit-* | sort -V | tail -1)"

# the packages of the libraries Playwright's WebKit (WPE and GTK builds)
# needs beyond a desktop-less Ubuntu 24.04, and of their own dependencies
PACKAGES=(libavif16 libevent-2.1-7t64 libgstreamer-plugins-base1.0-0 libgstreamer-gl1.0-0
  libgstreamer-plugins-bad1.0-0 libharfbuzz-icu0 libhyphen0 libwayland-server0 libwebpdemux2
  libwoff1 libegl1 libgav1-1 liborc-0.4-0t64 libyuv0 libglvnd0 libegl-mesa0 libabsl20220623t64
  libenchant-2-2 libgraphene-1.0-0 libgtk-4-1 libmanette-0.2-0 libsecret-1-0 libgles2
  libcairo-script-interpreter2 mesa-libgallium)

if [[ ! -d "$LIBDIR" ]]; then
  mkdir -p "$OUT/debs"
  (cd "$OUT/debs" && apt-get download "${PACKAGES[@]}" >&2)
  for deb in "$OUT"/debs/*.deb; do dpkg -x "$deb" "$OUT/root"; done
fi

cat >"$OUT/webkit.sh" <<EOF
#!/bin/sh
# Generated by scripts/webkit-local-libs.sh: Playwright's MiniBrowser with
# the libraries of $LIBDIR.
case " \$* " in
  *" --headless "*) D="$WEBKIT/minibrowser-wpe" ;;
  *) D="$WEBKIT/minibrowser-gtk" ;;
esac
export WEBKIT_EXEC_PATH="\$D/bin" WEBKIT_INJECTED_BUNDLE_PATH="\$D/lib" WEBKIT_INSPECTOR_RESOURCES_PATH="\$D/share"
export LD_LIBRARY_PATH="\$D/lib:\$D/sys/lib:$LIBDIR"
export __EGL_VENDOR_LIBRARY_DIRS="$OUT/root/usr/share/glvnd/egl_vendor.d"
export WEBKIT_FORCE_COMPLEX_TEXT=1
exec "\$D/bin/MiniBrowser" "\$@"
EOF
chmod +x "$OUT/webkit.sh"
echo "$OUT/webkit.sh"
