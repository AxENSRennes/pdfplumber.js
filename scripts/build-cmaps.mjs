#!/usr/bin/env node
// Builds dist/cmaps/: pdfminer's predefined CMaps, in the compact form of
// oracle/codegen/cmaps.py, zlib-compressed (docs/js-runtime.md, "CMaps").
//
//   node scripts/build-cmaps.mjs [--dir DIR] [--out dist/cmaps]
//   node scripts/build-cmaps.mjs --write-names   # regenerate js/src/generated/cmap-names.ts
//   node scripts/build-cmaps.mjs --check-names   # exit 1 unless it is up to date
//
// DIR defaults to the directory `python -m oracle.codegen.cmaps` prints (it
// converts pdfminer's files on first use, under <cache>/cmap/<fingerprint>/),
// run with $PDFPLUMBER_ROOT/.venv/bin/python. zlib (not gzip or brotli):
// the core inflates the files itself with its port of zlib, so every runtime
// decodes them with the same code and no DecompressionStream is needed; a
// server that compresses on the fly (Content-Encoding) changes nothing.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync, constants } from "node:zlib";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const NAMES_TS = join(ROOT, "js/src/generated/cmap-names.ts");

const args = process.argv.slice(2);
const opt = (name, dflt) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : dflt;
};

function cmapDir() {
  const given = opt("--dir");
  if (given) return given;
  const root = process.env.PDFPLUMBER_ROOT ?? ROOT;
  const out = execFileSync(join(root, ".venv/bin/python"), ["-m", "oracle.codegen.cmaps"], {
    cwd: ROOT,
    env: { ...process.env, PYTHONPATH: ROOT, PDFPLUMBER_ROOT: root },
    encoding: "utf8",
  });
  return out.trim().split("\n").pop().split(" (")[0];
}

function namesModule(names) {
  return (
    "// Generated by scripts/build-cmaps.mjs --write-names from the names of\n" +
    "// pdfminer's predefined CMaps (oracle/codegen/cmaps.py): do not edit.\n\n" +
    "/** The predefined CMaps (`pdfminer/cmap/<name>.json.gz`). */\n" +
    "export const CMAP_NAMES: readonly string[] = Object.freeze([\n" +
    names.map((n) => `  ${JSON.stringify(n)},\n`).join("") +
    "]);\n"
  );
}

const dir = cmapDir();
const names = readFileSync(join(dir, "names.txt"), "utf8").split("\n").filter(Boolean);

if (args.includes("--write-names")) {
  writeFileSync(NAMES_TS, namesModule(names));
  console.log(`wrote ${NAMES_TS} (${names.length} names)`);
  process.exit(0);
}
if (args.includes("--check-names")) {
  let current = "";
  try {
    current = readFileSync(NAMES_TS, "utf8");
  } catch {}
  if (current !== namesModule(names)) {
    console.error(`${NAMES_TS} is stale: run node scripts/build-cmaps.mjs --write-names`);
    process.exit(1);
  }
  console.log(`${NAMES_TS} is up to date (${names.length} names)`);
  process.exit(0);
}

const out = resolve(opt("--out", join(ROOT, "dist/cmaps")));
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
let raw = 0;
let packed = 0;
for (const name of names) {
  const data = readFileSync(join(dir, `${name}.pdfcmap`));
  const z = deflateSync(data, { level: constants.Z_BEST_COMPRESSION });
  writeFileSync(join(out, `${encodeURIComponent(name)}.pdfcmap.zlib`), z);
  raw += data.length;
  packed += z.length;
}
const extra = readdirSync(dir).filter((f) => f.endsWith(".pdfcmap")).length - names.length;
if (extra !== 0) throw new Error(`${dir}: ${extra} files not listed in names.txt`);
console.log(`${out}: ${names.length} CMaps, ${raw} bytes compact, ${packed} bytes zlib`);
