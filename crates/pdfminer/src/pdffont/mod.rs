/// `data[:n]` for a Python int `n`.
fn slice_prefix(data: &[u8], n: &PyInt) -> Vec<u8> {
    let len = data.len() as i64;
    let end = match n.as_i64() {
        Some(n) if n < 0 => (len + n).max(0),
        Some(n) => n.min(len),
        None if n.is_negative() => 0,
        None => len,
    };
    data[..end as usize].to_vec()
}

