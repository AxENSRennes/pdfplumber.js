/// The font of a font dictionary, as `PDFResourceManager.get_font(None,
/// spec)` creates it: the class by `/Subtype` (a `Type0` font is its first
/// descendant, with the parent's `/Encoding` and `/ToUnicode`); the cache
/// of the resource manager is not here. Takes `get_font`'s frame.
pub fn get_font(spec: &PDFDict) -> PyResult<PDFFont> {
    let _frame = frames::frame()?;
    // log.debug("get_font: create: objid=%r, spec=%r", objid, spec)
    frames::log_frames(Logger::PdfInterp, Level::Debug)?;
    // Create a Font object.
    let subtype = match spec.get("Subtype") {
        Some(s) => lit_name(&s)?,
        None => {
            if settings::STRICT {
                return Err(exc::PDFFontError("Font Subtype is not specified."));
            }
            "Type1".to_owned()
        }
    };
    match subtype.as_str() {
        // Type1 Font
        "Type1" | "MMType1" => PDFFont::new_type1(spec, false),
        // TrueType Font
        "TrueType" => PDFFont::new_type1(spec, true),
        // Type3 Font
        "Type3" => PDFFont::new_type3(spec),
        // CID Font
        "CIDFontType0" | "CIDFontType2" => PDFFont::new_cid(spec, settings::STRICT),
        "Type0" => {
            // Type0 Font
            let dfonts = list_value(&getitem(spec, "DescendantFonts")?)?;
            let Some(first) = dfonts.get(0) else {
                return Err(exc::AssertionError(""));
            };
            let subspec = dict_value(&first)?.copy();
            for k in ["Encoding", "ToUnicode"] {
                if let Some(v) = spec.get(k) {
                    subspec.insert(Rc::from(k), resolve1(&v)?);
                }
            }
            get_font(&subspec)
        }
        // this is so wrong!
        _ => PDFFont::new_type1(spec, false),
    }
}

