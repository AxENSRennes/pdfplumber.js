/// `(a, b) = x` for an object `x` (a resolved `/DW2`): a list, the keys of
/// a dict, the bytes of a string; a stream is iterated through its
/// `__getitem__`, which raises `PDFKeyError`; anything else is not
/// iterable.
fn unpack2(x: &PDFObject) -> PyResult<(IterItem, IterItem)> {
    let items: Vec<IterItem> = match x {
        PDFObject::List(l) => l.to_vec().into_iter().map(IterItem::Obj).collect(),
        PDFObject::Dict(d) => d.keys().into_iter().map(IterItem::Str).collect(),
        PDFObject::Bytes(b) => b.iter().map(|&c| IterItem::Obj(PDFObject::Int(PyInt::Small(i64::from(c))))).collect(),
        PDFObject::Stream(_) => {
            drop(frames::c_called()?); // PDFStream.__getitem__(0), from C
            x.py_getitem_index0()?;
            unreachable!("a stream has no attribute 0")
        }
        other => return Err(exc::TypeError(format!("cannot unpack non-iterable {} object", other.type_name()))),
    };
    let [a, b] = unpack::<_, 2>(&items)?;
    Ok((a, b))
}

/// `bytes.decode("latin1")` of a resolved `/Registry` or `/Ordering`.
fn decode_latin1(x: &PDFObject) -> PyResult<String> {
    match x {
        PDFObject::Bytes(b) => Ok(b.iter().map(|&c| char::from(c)).collect()),
        PDFObject::Stream(_) => Err(exc::TypeError("PDFStream.decode() takes 1 positional argument but 2 were given")),
        other => Err(exc::AttributeError(format!("'{}' object has no attribute 'decode'", other.type_name()))),
    }
}

