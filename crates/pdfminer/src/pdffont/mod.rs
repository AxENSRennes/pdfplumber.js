/// `for i in range(char1, char2 + 1)` over Python ints.
fn int_range(char1: &PyInt, char2: &PyInt, mut f: impl FnMut(&PyInt)) {
    let end = char2.add(&PyInt::Small(1));
    let mut i = char1.clone();
    while i < end {
        f(&i);
        i = i.add(&PyInt::Small(1));
    }
}

/// `char1 + i` for a number `char1` (an `int`, `float` or `bool`).
fn plus(char1: &Num, i: usize) -> PyResult<NumKey> {
    Ok(NumKey::new(char1.add(&Num::Int(PyInt::Small(i as i64)))?))
}

/// The number of a PDF object for `isinstance(v, (int, float))`.
fn number(v: &PDFObject) -> Option<Num> {
    v.as_num()
}

/// The int of `isinstance(x, int)` (a `bool` included).
fn int_of(v: &PDFObject) -> Option<PyInt> {
    match v {
        PDFObject::Int(i) => Some(i.clone()),
        PDFObject::Bool(b) => Some(PyInt::Small(i64::from(*b))),
        _ => None,
    }
}

