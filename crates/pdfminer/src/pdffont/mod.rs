/// Build a mapping of character widths for horizontal writing.
pub fn get_widths(seq: &PDFList) -> PyResult<FontWidthDict> {
    let _frame = frames::frame()?;
    let mut widths = FontWidthDict::default();
    let mut r: Vec<PDFObject> = Vec::new();
    let mut k = 0;
    while let Some(v) = seq.get(k) {
        k += 1;
        let v = resolve1(&v)?;
        if let PDFObject::List(v) = &v {
            if let Some(char1) = r.last() {
                let char1 = number(char1).expect("r holds numbers");
                for (i, w) in v.to_vec().into_iter().enumerate() {
                    widths.insert(WidthKey::Num(plus(&char1, i)?), w);
                }
                r.clear();
            }
        } else if number(&v).is_some() {
            r.push(v);
            if r.len() == 3 {
                let [char1, char2, w] = unpack::<_, 3>(&r)?;
                if let (Some(char1), Some(char2)) = (int_of(&char1), int_of(&char2)) {
                    int_range(&char1, &char2, |i| {
                        widths.insert(WidthKey::int(i), w.clone());
                    });
                } else {
                    // log.warning("Skipping invalid font width specification ...")
                    frames::log_frames(Logger::PdfFont, Level::Warning)?;
                }
                r.clear();
            }
        } else {
            // log.warning("Skipping invalid font width specification ...")
            frames::log_frames(Logger::PdfFont, Level::Warning)?;
        }
    }
    Ok(widths)
}

/// `range(x, ...)` of a number: a float is not an integer.
fn range_int(x: &Num) -> PyResult<PyInt> {
    match x {
        Num::Int(i) => Ok(i.clone()),
        Num::Float(_) => Err(exc::TypeError("'float' object cannot be interpreted as an integer")),
    }
}

// pdfminer/pdffont.py:90 get_widths2
/// Build a mapping of character widths for vertical writing.
pub fn get_widths2(seq: &PDFList) -> PyResult<Widths2> {
    let _frame = frames::frame()?;
    let mut widths = Widths2::default();
    let mut r: Vec<PDFObject> = Vec::new();
    let mut k = 0;
    while let Some(v) = seq.get(k) {
        k += 1;
        if let PDFObject::List(v) = &v {
            if let Some(char1) = r.last() {
                let char1 = number(char1).expect("r holds numbers");
                // enumerate(choplist(3, v)): the generator is resumed from C
                // once per triple, and once more to finish
                let items = v.to_vec();
                let triples = items.as_chunks::<3>().0.iter();
                for (i, t) in triples.enumerate() {
                    drop(frames::c_called()?);
                    widths.insert(plus(&char1, i)?, (t[0].clone(), (t[1].clone(), t[2].clone())));
                }
                drop(frames::c_called()?);
                r.clear();
            }
        } else if number(&v).is_some() {
            r.push(v);
            if r.len() == 5 {
                let [char1, char2, w, vx, vy] = unpack::<_, 5>(&r)?;
                let char1 = range_int(&number(&char1).expect("a number"))?;
                let char2 = number(&char2).expect("a number").add(&Num::Int(PyInt::Small(1)))?;
                let end = range_int(&char2)?.sub(&PyInt::Small(1));
                int_range(&char1, &end, |i| {
                    widths.insert(NumKey::new(Num::Int(i.clone())), (w.clone(), (vx.clone(), vy.clone())));
                });
                r.clear();
            }
        }
    }
    Ok(widths)
}

