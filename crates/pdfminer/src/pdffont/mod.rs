/// `x * scale` for a value `x` that may be a `str` (a key of `/DW2`).
/// A `str` is only ever multiplied by a `float` scale: only a CID font has
/// a `str` default width, and its scale is `0.001`.
fn item_mul(x: &IterItem, scale: &Operand) -> PyResult<Operand> {
    match item_operand(x) {
        Some(x) => x.mul(scale),
        None => match scale {
            Operand::Num(Num::Float(_)) => Err(exc::TypeError("can't multiply sequence by non-int of type 'float'")),
            other => unreachable!("a str default width with the scale {other:?}"),
        },
    }
}

