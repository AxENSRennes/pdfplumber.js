//! Port of `pdfminer/pdffont.py`: the font classes the interpreter shows
//! text with, and the parsers of the embedded font programs they read.
//!
//! The module is a directory: [`type1`] (`Type1FontHeaderParser`), [`cff`]
//! (`NIBBLES`, `getdict`, `CFFFont`), [`truetype`] (`TrueTypeFont`),
//! [`tables`] (generated from upstream), and two helpers of the port:
//! [`frames`] (the Python frames of the calls pdffont makes into modules
//! that do not count their own) and [`unpack`] (`struct.unpack` and
//! `BytesIO` semantics). Everything else is here.
//!
//! # Classes
//!
//! `PDFFont`, `PDFSimpleFont`, `PDFType1Font`, `PDFTrueTypeFont`,
//! `PDFType3Font` and `PDFCIDFont` are one struct, [`PDFFont`]: the
//! attributes of `PDFFont.__init__` (shared by every class) and the data of
//! the concrete class ([`FontKind`]). The methods dispatch on the class
//! where a subclass overrides them. [`get_font`] is the font-creating part
//! of `PDFResourceManager.get_font` (the dispatch on `/Subtype`, `Type0`
//! fonts included), without its cache, which stays with the resource
//! manager (`pdfinterp`).
//!
//! # Values
//!
//! The font code runs on unchecked PDF objects, and Python's dynamic types
//! show in its results:
//!
//! - widths are a dict whose keys are character codes (an `int`, or a
//!   `float` when a `/W` array starts a run with a real number: `1.5 + i`)
//!   or, for the 14 standard fonts, `str` characters ([`WidthKey`], with
//!   Python's `hash`/`==`: `65.0` finds `65`), and whose values are any
//!   object (`safe_float` reads them);
//! - `ascent`, `descent`, `italic_angle`, `leading` are what `num_value`
//!   returns: an `int`, a `float` or a `bool` (an `int` subclass, kept as
//!   such: `-True` is `-1`); `default_width` is any object (`/DW`, an item
//!   of `/DW2`: a dict's key is a `str`, so an [`IterItem`]);
//! - `hscale`/`vscale` are `0.001`, but a Type 3 font computes them from
//!   its `/FontMatrix` items with Python's operators ([`Operand`]): ints,
//!   or a `bytes`/`list` repeated and concatenated, so `char_width` and the
//!   `get_*` methods return an [`Operand`] (a number in practice);
//! - text is cmapdb's [`Unichr`] (`IdentityUnicodeMap` gives `chr(cid)`,
//!   which can be a lone surrogate).
//!
//! # Recursion depth
//!
//! Every ported function takes its Python frame, and the calls into
//! modules that do not count theirs take them through [`frames`], so that a
//! font built or queried at the depth of a nested Form XObject raises
//! `RecursionError` where Python does (`docs/architecture.md`). A class
//! instantiation is a call from C (`type.__call__` runs `__init__`).
//! `cmapdb` counts the frames of `CMapDB` (loading a predefined CMap
//! included) and of the `CMapParser` methods; the parsers' construction
//! takes the frames of `PSStackParser.__init__`. What is not modeled, and
//! documented where it happens: the frames of `psparser` below
//! `nextobject` (never deeper than the parser's construction, which comes
//! first), of the filters below `PDFStream.decode` other than Flate, and the
//! import of the UTF-16 codec by the first `bytes.decode("UTF-16BE")` of a
//! Python process.

