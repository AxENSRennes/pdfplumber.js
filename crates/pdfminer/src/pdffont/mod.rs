/// A font descriptor: a dict of the PDF, or the descriptor of a standard
/// font (`FONT_METRICS`), whose values are Python `str`, `int`, `float` and
/// tuples of floats.
#[derive(Clone)]
pub enum Descriptor {
    Dict(PDFDict),
    Metrics(&'static FontMetrics),
}

/// A value of a [`Descriptor`].
#[derive(Clone, Debug)]
pub enum DescValue {
    Obj(PDFObject),
    Str(&'static str),
    /// A tuple of floats (`FontBBox` of a standard font).
    Tuple(&'static [f64]),
}

impl DescValue {
    /// The PDF object for the accessors (`int_value`, `num_value`, which
    /// give 0 for anything but a number; a `str` or a tuple is not one).
    fn as_obj(&self) -> PDFObject {
        match self {
            DescValue::Obj(o) => o.clone(),
            DescValue::Str(_) | DescValue::Tuple(_) => PDFObject::Null,
        }
    }
}

impl Descriptor {
    /// `descriptor.get(key)`
    pub fn get(&self, key: &str) -> Option<DescValue> {
        match self {
            Descriptor::Dict(d) => d.get(key).map(DescValue::Obj),
            Descriptor::Metrics(m) => m.descriptor.iter().find(|(k, _)| *k == key).map(|(_, v)| match v {
                FontMetricValue::Str(s) => DescValue::Str(s),
                FontMetricValue::Int(i) => DescValue::Obj(PDFObject::Int(PyInt::Small(*i))),
                FontMetricValue::Float(f) => DescValue::Obj(PDFObject::Float(*f)),
                FontMetricValue::FloatTuple(t) => DescValue::Tuple(t),
            }),
        }
    }

    /// `key in descriptor`
    pub fn contains(&self, key: &str) -> bool {
        self.get(key).is_some()
    }

    /// `descriptor.get(key, default)` as a PDF object for an accessor.
    fn get_obj(&self, key: &str, default: PDFObject) -> PDFObject {
        self.get(key).map_or(default, |v| v.as_obj())
    }
}

