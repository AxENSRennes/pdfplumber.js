/// Get cmap name from font specification: `/Encoding`'s name, or its
/// `/CMapName` when it is a dict or a stream, mapped by
/// `IDENTITY_ENCODER`; `"unknown"` when missing.
pub fn get_cmap_name(spec: &PDFDict, strict: bool) -> PyResult<String> {
    let _frame = frames::frame()?;
    let mut cmap_name = "unknown".to_owned(); // default value
    let attempt = (|| -> PyResult<String> {
        let spec_encoding = getitem(spec, "Encoding")?;
        match &spec_encoding {
            // hasattr(spec_encoding, "name"): literals and keywords
            PDFObject::Literal(_) | PDFObject::Keyword(_) => lit_name(&spec_encoding),
            PDFObject::Dict(d) => lit_name(&getitem(d, "CMapName")?),
            PDFObject::Stream(s) => lit_name(&stream_getitem(s, "CMapName")?),
            PDFObject::List(_) => Err(exc::TypeError("list indices must be integers or slices, not str")),
            PDFObject::Bytes(_) => Err(exc::TypeError("byte indices must be integers or slices, not str")),
            other => Err(exc::TypeError(format!("'{}' object is not subscriptable", other.type_name()))),
        }
    })();
    match key_error(attempt)? {
        Ok(name) => cmap_name = name,
        Err(_) => {
            if strict {
                return Err(exc::PDFFontError("Encoding is unspecified"));
            }
        }
    }
    // `type(cmap_name) is PDFStream` is never true: literal_name returns a
    // str.
    Ok(identity_encoder(&cmap_name).to_owned())
}

